import {readFile,writeFile,mkdir,mkdtemp,cp,rm,readdir} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {resolve,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {gunzipSync} from 'node:zlib';
import {spawnSync} from 'node:child_process';
import assert from 'node:assert/strict';
import {build} from 'vite';
import react from '@vitejs/plugin-react';
const root=resolve(fileURLToPath(new URL('../',import.meta.url)));
const registry=JSON.parse(await readFile(join(root,'delivery/components.json')));
const catalog=JSON.parse(await readFile(join(root,'assets/ai-deliveries/manifest.json')));
const temp=await mkdtemp(join(tmpdir(),'aisee-production-recipient-'));
const hash=content=>createHash('sha256').update(content).digest('hex');
const results=[];
try {
  const entries=[];
  for(const manifest of registry.components) {
    const entry=catalog[manifest.page];assert.ok(entry,manifest.name);
    const bundle=JSON.parse(await readFile(join(root,entry.url),'utf8'));
    const base=join(root,'assets/ai-deliveries',manifest.slug);
    const latest=JSON.parse(await readFile(join(base,'latest.json')));
    assert.equal(latest.version,bundle.version);
    assert.equal(latest.name,manifest.name);
    assert.deepEqual(latest.compatibility,manifest.compatibility);
    assert.deepEqual(bundle.compatibility,manifest.compatibility);
    const installer=await readFile(join(base,latest.installer),'utf8');
    const guide=await readFile(join(base,latest.delivery),'utf8');
    assert.equal(hash(installer),latest.installerSha256);
    assert.ok(guide.includes(latest.installerSha256));
    const files=JSON.parse(gunzipSync(Buffer.from(bundle.payload,'base64')));
    assert.deepEqual(Object.keys(files),bundle.files);
    assert.deepEqual(Object.keys(files),latest.files);
    for(const path of Object.keys(files)) assert.doesNotMatch(path,/(?:^|[/_.-])(?:demo|playground|showcase|mock|fonts)(?:[/_.-]|$)|\.(?:woff2?|ttf|otf)$/i);
    const css=Buffer.from(files['styles.css'],'base64').toString();
    assert.doesNotMatch(css,/@import|@font-face|:root|font-family:\s*Karla/);
    await writeFile(join(temp,'install.cjs'),installer);
    const install=()=>spawnSync(process.execPath,['install.cjs',`src/${manifest.slug}`],{cwd:temp,encoding:'utf8'});
    const first=install();assert.equal(first.status,0,first.stderr);
    assert.equal(install().status,0,'Same source reinstall');
    const installed=join(temp,'src',manifest.slug);
    const actual=await readdir(installed,{recursive:true,withFileTypes:true});
    assert.equal(actual.filter(d=>d.isFile()).length,bundle.fileCount,'No hidden extras installed');
    const localEntry=join(installed,manifest.entries[0].split('/').pop());
    const original=await readFile(localEntry);
    await writeFile(localEntry,'// recipient work');
    assert.notEqual(install().status,0,'Refuse overwrite');
    assert.equal(await readFile(localEntry,'utf8'),'// recipient work');
    await writeFile(localEntry,original);
    await writeFile(join(temp,'install.cjs'),installer.replace(bundle.sha256,'0'.repeat(64)));
    assert.notEqual(install().status,0,'Reject corrupted payload');
    entries.push(`export * as ${manifest.name} from './${manifest.slug}/index';`);
    results.push({name:manifest.name,version:bundle.version,files:bundle.files,status:'pass'});
  }
  for(const dep of ['react','react-dom','scheduler','@types/react','@types/react-dom','csstype']) await cp(join(root,'node_modules',dep),join(temp,'node_modules',dep),{recursive:true});
  await writeFile(join(temp,'package.json'),'{"name":"isolated-production-recipient","type":"module","private":true}');
  await writeFile(join(temp,'src/index.ts'),entries.join('\n'));
  await writeFile(join(temp,'tsconfig.json'),JSON.stringify({compilerOptions:{target:'ES2022',module:'ESNext',moduleResolution:'Bundler',jsx:'react-jsx',strict:true,noEmit:true,skipLibCheck:false,lib:['DOM','ES2022']},include:['src']}));
  const types=spawnSync(process.execPath,[join(root,'node_modules/typescript/bin/tsc'),'-p','tsconfig.json'],{cwd:temp,encoding:'utf8'});
  assert.equal(types.status,0,types.stdout+types.stderr);
  await build({root:temp,configFile:false,plugins:[react()],logLevel:'error',build:{lib:{entry:join(temp,'src/index.ts'),formats:['es']},rollupOptions:{external:['react','react-dom','react/jsx-runtime']}}});
  // A real browser fixture, generated from the unpacked recipient files, not the DS demo.
  await writeFile(join(temp,'index.html'),'<html><head><meta charset="UTF-8"></head><body><div id="root"></div><script type="module" src="/runtime.tsx"></script></body></html>');
  await writeFile(join(temp,'runtime.tsx'),await readFile(join(root,'tests/fixtures/production-runtime.tsx'),'utf8'));
  await build({root:temp,configFile:false,plugins:[react()],base:'./',logLevel:'error',build:{outDir:join(root,'artifacts/production-delivery-runtime'),emptyOutDir:true}});
  await mkdir(join(root,'artifacts/production-delivery-audit'),{recursive:true});
  await writeFile(join(root,'artifacts/production-delivery-audit/report.json'),JSON.stringify({registeredComponents:registry.components.length,verifiedDeliveries:results.length,components:results.length,isolatedTypecheck:'pass',isolatedBuild:'pass',browserRuntime:'Run artifacts/production-delivery-runtime/index.html',results},null,2));
  console.log(`Registered components: ${registry.components.length}\nVerified deliveries: ${results.length}`);
  console.log(`PASS: ${results.length} independent production deliveries, exact file lists, no demo/fonts/global CSS, checksum/reinstall/conflict checks, isolated React typecheck and build. Browser fixture generated.`);
} finally {await rm(temp,{recursive:true,force:true});}
